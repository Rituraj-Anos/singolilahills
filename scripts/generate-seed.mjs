// Writes supabase/seed.sql from the bundled content in lib/data, so the database starts with today's site.
// Run: node scripts/generate-seed.mjs
import fs from 'node:fs';
import { PACKAGES } from '../lib/data/packages.js';
import { DESTINATIONS } from '../lib/data/destinations.js';
import { BLOGS } from '../lib/data/blogs.js';
import { REELS } from '../lib/data/reels.js';
import { REVIEWS } from '../lib/data/reviews.js';
import { DEFAULT_SETTINGS, FAQS } from '../lib/data/settings.js';

// dollar-quoting with a tag that never appears in the data keeps the JSON exactly as is
const lit = (v) => {
  const s = JSON.stringify(v);
  if (s.includes('$seed$')) throw new Error('seed tag found in data');
  return `$seed$${s}$seed$::jsonb`;
};
// timestamps are set explicitly: jsonb_populate_recordset would otherwise pass NULL into NOT NULL columns
const now = new Date().toISOString();
const insert = (table, rows) =>
  `insert into public.${table} select * from jsonb_populate_recordset(null::public.${table}, ${lit(
    rows.map((r) => ({ created_at: now, updated_at: now, ...r }))
  )}) on conflict (id) do nothing;`;

const packages = PACKAGES.map((p, i) => ({ ...p, published: true, sort_order: i }));
const destinations = DESTINATIONS.map((d, i) => ({ ...d, published: true, sort_order: i }));
const posts = BLOGS.map(({ date, ...b }) => ({ ...b, published_at: date, published: true }));
const reels = REELS.map(({ reelUrl, ...r }, i) => ({ ...r, reel_url: reelUrl, sort_order: i, published: false }));
// sample reviews arrive hidden: publish only the ones confirmed as real
const reviews = REVIEWS.map((r) => ({ ...r, published: false }));
const faqs = FAQS.map((f) => ({ ...f, published: true }));

const sql = `-- Generated by scripts/generate-seed.mjs. Run once after the migrations.
-- Sample reels (placeholder links) and sample reviews are inserted hidden; check and publish them in the admin.
begin;
${insert('packages', packages)}
${insert('destinations', destinations)}
${insert('posts', posts)}
${insert('reels', reels)}
${insert('reviews', reviews)}
${insert('faqs', faqs)}
update public.site_settings set data = ${lit(DEFAULT_SETTINGS)} where id = 1 and data = '{}'::jsonb;
commit;
`;
fs.writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('wrote supabase/seed.sql', { packages: packages.length, destinations: destinations.length, posts: posts.length, reels: reels.length, reviews: reviews.length, faqs: faqs.length });
